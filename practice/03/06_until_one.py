"""
1이 될 때까지

어떠한 수 N이 1이 될 때까지 다음의 두 과정 중 하나를 반복적으로 선택하여
수행하려고 한다. 단, 두 번째 연산은 N이 K로 나누어떨어질 때만 선택할 수 있다.

    1. N에서 1을 뺀다.
    2. N을 K로 나눈다.

예를 들어 N이 17, K가 4라고 가정하자. 이때 1번의 과정을 한 번 수행하면 N은 16이 된다.
이후에 2번의 과정을 두 번 수행하면 N은 1이 된다. 결과적으로 이 경우 전체 과정을
실행한 횟수는 3이 된다. 이는 N을 1로 만드는 최소 횟수이다.

N과 K가 주어질 때 N이 1이 될 때까지 1번 혹은 2번의 과정을 수행해야 하는 최소 횟수를
구하는 프로그램을 작성하시오.

입력 조건
- 첫째 줄에 N(2 <= N <= 100,000)과 K(2 <= K <= 100,000)가 공백으로 구분되며 각각
  자연수로 주어진다. 이때 입력으로 주어지는 N은 항상 K보다 크거나 같다.

출력 조건
- 첫째 줄에 N이 1이 될 때까지 1번 혹은 2번의 과정을 수행해야 하는 횟수의 최솟값을
  출력한다.

예제 입력 1        예제 출력 1
25 5               2

예제 입력 2        예제 출력 2
17 4               3

── 생각할 거리 ───────────────────────────────────────────────
"최소 횟수"를 물었으니 그리디다. 매 순간 어느 쪽이 이득인지 판단해야 한다.

N = 25, K = 5 일 때
    1을 빼는 길:  25 → 24 → 23 → ... → 1      (24번)
    K로 나누는 길: 25 → 5 → 1                  (2번)

나누기가 훨씬 빨리 줄어든다. 그렇다면 전략은?
그리고 나누어떨어지지 않을 때는 어떻게 해야 할까?
─────────────────────────────────────────────────────────────

테스트:
    printf '25 5\n' | python3 practice/03/06_until_one.py
    printf '17 4\n' | python3 practice/03/06_until_one.py
"""


n, k = map(int, input().split())

count = 0
while n > 1 :
  if n % k == 0:
    n = n / k
  else:
    n -= 1
  count += 1

print(count)

