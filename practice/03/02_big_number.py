"""
큰 수의 법칙

다양한 수로 이루어진 배열이 있을 때 주어진 수들을 M번 더하여 가장 큰 수를 만드는
법칙이다. 단, 배열의 특정한 인덱스(번호)에 해당하는 수가 연속해서 K번을 초과하여
더해질 수 없는 것이 이 법칙의 특징이다.

예를 들어 순서대로 2, 4, 5, 4, 6으로 이루어진 배열이 있을 때 M이 8이고, K가 3이라고
가정하자. 이 경우 특정한 인덱스의 수가 연속해서 세 번까지만 더해질 수 있으므로
6 + 6 + 6 + 5 + 6 + 6 + 6 + 5 인 46이 큰 수의 법칙에 따른 결과가 된다.

단, 배열에 중복되는 수가 있는 경우 서로 다른 인덱스로 취급한다. 예컨대 3, 4, 3, 4, 3
배열에서 M이 7, K가 2라면 두 번째 원소(4)와 네 번째 원소(4)를 번갈아 더할 수 있으므로
4 + 4 + 4 + 4 + 4 + 4 + 4 인 28이 된다.

배열의 크기 N, 숫자가 더해지는 횟수 M, 그리고 K가 주어질 때 큰 수의 법칙에 따른
결과를 출력하시오.

입력 조건
- 첫째 줄에 N(2 <= N <= 1,000), M(1 <= M <= 10,000), K(1 <= K <= 10,000)의 자연수가
  주어지며, 각 자연수는 공백으로 구분한다. (단, K <= M)
- 둘째 줄에 N개의 자연수가 주어진다. 각 자연수는 공백으로 구분한다.
  단, 각각의 자연수는 1 이상 10,000 이하의 수로 주어진다.

출력 조건
- 첫째 줄에 큰 수의 법칙에 따라 더해진 답을 출력한다.

예제 입력 1        예제 출력 1
5 8 3              46
2 4 5 4 6

예제 입력 2        예제 출력 2
5 7 2              28
3 4 3 4 3
"""

n, m, k = map(int, input().split())
nums= list(map(int, input().split()))

nums.sort() 
again = 0
sum = 0

while m > 0:
  if(again >= k):
    sum += nums[-2]
    again = 0
  else:
    sum += nums[-1]
    again += 1
  m -= 1

print(sum)

# ─────────────────────────────────────────────────────────────
# 풀이 2 — 수식으로 계산 (O(1))
#
# M번 중 (K+1)개가 한 묶음. 묶음마다 큰 수 K개 + 둘째 수 1개가 들어가고,
# 묶음을 채우지 못한 자투리(m % (k+1))는 연속 제한에 안 걸리므로 전부 큰 수.
