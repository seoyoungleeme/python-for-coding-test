"""
시각

정수 N이 입력되면 00시 00분 00초부터 N시 59분 59초까지의 모든 시각 중에서 3이
하나라도 포함되는 모든 경우의 수를 구하는 프로그램을 작성하시오. 예를 들어 1을
입력했을 때 다음은 3이 포함되어 있으므로 세어야 하는 시각이다.

    00시 00분 03초
    00시 13분 30초

반면에 다음은 3이 포함되어 있지 않으므로 세면 안 되는 시각이다.

    00시 02분 55초
    01시 27분 45초

입력 조건
- 첫째 줄에 정수 N이 입력된다. (0 <= N <= 23)

출력 조건
- 00시 00분 00초부터 N시 59분 59초까지의 모든 시각 중에서 3이 하나라도 포함되는
  모든 경우의 수를 출력한다.

예제 입력      예제 출력
5             11475

── 생각할 거리 ───────────────────────────────────────────────
N이 최대 23이어도 경우의 수는 24 * 60 * 60 = 86,400. 완전 탐색으로 충분하다
(개념 노트 1,000만 기준 안에 넉넉히 들어온다).

워밍업 6번(has_digit), 8번(count_times)이 이 문제를 그대로 합친 것이다.
시(hour), 분(minute), 초(second)를 문자열로 이어붙여서 '3'이 들어있는지
in 으로 검사하면 세 자리를 따로따로 검사할 필요가 없다.
─────────────────────────────────────────────────────────────

테스트:
    echo '5' | python3 practice/04/02_clock.py
"""


def solution(h):
    """
    h: 마지막 시각의 '시' (예: 5 → 00시 00분 00초부터 5시 59분 59초까지 검사)

    반환값: 3이 하나라도 포함된 시각의 개수
    """
    count = 0
    # TODO: 여기부터 구현

    one_count = (60-15)*15 + 15*60

    for i in range(h + 1):
        if i == 3 or i == 13 or i == 23:
            count += 60*60*1
        else:
            count += one_count
        
    return count


if __name__ == "__main__":
    h = int(input())
    print(solution(h))
