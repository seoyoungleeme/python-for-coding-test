"""
왕실의 나이트

행복 왕국의 왕실 정원은 체스판과 같은 8 x 8 좌표 평면이다. 왕실 정원의 특정한
한 칸에 나이트가 서 있다. 나이트는 매우 신비한 기사로 여겨지며, 이동을 할 때는
L자 형태로만 이동할 수 있고 정원 밖으로는 나갈 수 없다.

나이트는 다음과 같은 8가지 방향으로 이동할 수 있다. 단, 이때 8가지 방향 모두
정원의 밖으로 나가는 이동이라면 사용할 수 없다.

    1. 오른쪽으로 두 칸 이동한 뒤 아래로 한 칸 이동하기
    2. 오른쪽으로 두 칸 이동한 뒤 위로 한 칸 이동하기
    3. 왼쪽으로 두 칸 이동한 뒤 아래로 한 칸 이동하기
    4. 왼쪽으로 두 칸 이동한 뒤 위로 한 칸 이동하기
    5. 위로 두 칸 이동한 뒤 오른쪽으로 한 칸 이동하기
    6. 위로 두 칸 이동한 뒤 왼쪽으로 한 칸 이동하기
    7. 아래로 두 칸 이동한 뒤 오른쪽으로 한 칸 이동하기
    8. 아래로 두 칸 이동한 뒤 왼쪽으로 한 칸 이동하기

왕실 정원에서의 위치는 열과 행을 표현할 때 a1처럼 알파벳(열)과 숫자(행)를 함께
쓴다. 알파벳은 a부터 h까지, 숫자는 1부터 8까지다. 예를 들어 c4에서는 나이트가
이동할 수 있는 경우의 수가 8가지로 최대치이며, a1에서는 2가지밖에 존재하지
않는다.

나이트가 있는 위치가 주어졌을 때, 나이트가 이동할 수 있는 경우의 수를 출력하는
프로그램을 작성하시오.

입력 조건
- 첫째 줄에 8 x 8 좌표 평면상에서 현재 나이트가 위치한 곳의 좌표를 나타내는
  두 문자를 입력한다. 입력 문자는 a1처럼 열과 행으로 이뤄진다.

출력 조건
- 첫째 줄에 나이트가 이동할 수 있는 경우의 수를 출력한다.

예제 입력      예제 출력
a1            2

예제 입력      예제 출력
c2            6

── 생각할 거리 ───────────────────────────────────────────────
1. 워밍업 7번(to_index)으로 'a1' 같은 문자열을 (행, 열) 숫자로 바꾼다.
2. 나이트가 갈 수 있는 8가지 상대 이동을 (행 변화량, 열 변화량) 튜플 8개로
   미리 리스트에 적어둔다. (개념 노트의 dx, dy와 같은 발상 — 다만 이번엔
   4방향이 아니라 8방향이다.)
3. 8가지 각각에 대해 새 위치가 1~8 범위 안인지 확인하고, 안이면 개수를 센다.
   → 워밍업 3번(in_range)의 아이디어를 1~8 범위에 맞게 쓰면 된다.
─────────────────────────────────────────────────────────────

테스트:
    echo 'a1' | python3 practice/04/03_knight.py
    echo 'c2' | python3 practice/04/03_knight.py
"""


def solution(pos):
    """
    pos: 'a1' 같은 두 글자 문자열 (열 알파벳 + 행 숫자)

    반환값: 나이트가 이동할 수 있는 경우의 수
    """
    result = 0
    # TODO: 여기부터 구현
    # 위치 파악
    x, y = int(pos[1])-1, ord(pos[0]) - ord('a') # 0, 0부터 시작. (7, 7)까지

    moves = [(1, 2), (-1, 2), (1, -2), (-1, -2), (-2, 1), (-2, -1), (2, 1), (2, -1)]

    # for dx, dy in moves 가능
    for i in range(8):
        dx, dy = moves[i]
        if 0 <= x + dx < 8 and 0 <= y + dy < 8:
            result += 1

    return result


if __name__ == "__main__":
    pos = input()
    print(solution(pos))
