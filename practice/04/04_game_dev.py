"""
게임 개발

현민이는 게임 캐릭터가 맵 안에서 움직이는 시스템을 개발 중이다. 캐릭터가 있는
장소는 1 x 1 크기의 정사각형으로 이루어진 N x M 크기의 직사각형이며, 각각의
칸은 육지 또는 바다이다. 캐릭터는 상, 하, 좌, 우 중 하나의 방향을 바라본다.

맵의 각 칸은 (A, B)로 나타낼 수 있고, A는 북쪽으로부터 떨어진 칸의 개수, B는
서쪽으로부터 떨어진 칸의 개수다. 캐릭터는 처음에 정해진 위치와 방향에서
게임이 시작되며, 이때 방향은 4가지 중 하나다.

    0: 북쪽, 1: 동쪽, 2: 남쪽, 3: 서쪽

캐릭터는 상하좌우로 움직일 수 있고, 바다로 되어 있는 공간에는 갈 수 없다.
캐릭터의 움직임을 설정하는 방식은 다음과 같다.

    1. 현재 위치에서 현재 방향을 기준으로 왼쪽 방향(반시계 방향으로 90도 회전한
       방향)부터 차례대로 갈 수 있는지 확인한다.
    2. 왼쪽 방향에 아직 가보지 않은 칸이 존재한다면, 왼쪽 방향으로 회전한 다음
       왼쪽으로 한 칸을 전진한다. 왼쪽 방향에 가보지 않은 칸이 없다면, 왼쪽
       방향으로 회전만 하고 1단계로 돌아간다.
    3. 만약 네 방향 모두 이미 가본 칸이거나 바다로 되어 있는 칸이라면, 바라보고
       있는 방향을 유지한 채로 한 칸 뒤로 가고 1단계로 돌아간다. 단, 이때 뒤쪽
       방향이 바다인 칸이라 뒤로 갈 수 없는 경우에는 movement를 멈춘다.

캐릭터가 이동한 (움직이며 방문한) 칸의 수를 출력하는 프로그램을 만드시오.

입력 조건
- 첫째 줄에 맵의 세로 크기 N과 가로 크기 M을 공백으로 구분하여 입력한다.
  (3 <= N, M <= 50)
- 둘째 줄에 캐릭터의 X 좌표, Y 좌표와 캐릭터가 바라보는 방향 d가 각각 공백으로
  구분하여 주어진다. 방향 d의 값으로는 0, 1, 2, 3이 존재하며 각각 북, 동, 남,
  서를 의미한다.
- 셋째 줄부터 맵이 육지인지 바다인지에 대한 정보가 주어지며, N개의 줄에 맵의
  상태가 M개의 정수로 주어진다. 각 정수는 0(육지) 혹은 1(바다)이다. 처음에
  캐릭터가 위치한 칸은 항상 육지다.

출력 조건
- 첫째 줄에 이동한 칸의 수를 출력한다.

예제 입력          예제 출력
4 4               3
1 1 0
1 1 1 1
1 0 0 1
1 1 0 1
1 1 1 1

── 생각할 거리 ───────────────────────────────────────────────
4장 문제 중 가장 규칙이 복잡하다. 코드부터 쓰지 말고 순서대로 적어보자.

1. 방문한 칸을 기록할 N x M 크기의 0으로 채운 맵을 하나 더 만든다.
   (개념 노트의 [[0] * m for _ in range(n)])
2. 시작 위치를 방문 처리한다.
3. 반복:
   a. 왼쪽으로 회전한다 (워밍업 5번 turn_left, 반시계 방향).
   b. 회전한 방향의 앞칸이 "육지이면서 아직 안 가본 칸"이면 그쪽으로 전진하고,
      회전 실패 횟수를 0으로 리셋한다.
   c. 아니면 회전만 유지하고, 회전 실패 횟수를 1 늘린다.
   d. 회전 실패가 4번(네 방향 다 막힘) 누적되면: 뒤로 갈 수 있으면 한 칸
      후진, 아니면 종료.
4. 종료될 때까지 방문한 칸 수를 센다.

"왼쪽 회전"과 "전진"은 서로 다른 동작이다 — 회전만 하고 전진은 안 할 수도
있다는 점이 이 문제의 함정이다.
─────────────────────────────────────────────────────────────

테스트:
    printf '4 4\n1 1 0\n1 1 1 1\n1 0 0 1\n1 1 0 1\n1 1 1 1\n' | python3 practice/04/04_game_dev.py
"""


def solution(n, m, x, y, direction, board):
    """
    n, m: 맵의 세로(N), 가로(M) 크기
    x, y: 캐릭터의 시작 좌표 (0부터 시작)
    direction: 캐릭터가 바라보는 방향 (0=북, 1=동, 2=남, 3=서)
    board: N x M 맵. board[i][j] 는 0(육지) 또는 1(바다)

    반환값: 캐릭터가 이동하며 방문한 칸의 수
    """
    # TODO: 여기부터 구현

    count = 0

    tries = 0
    visited = [[0]*m for _ in range(n)] # 2차원 배열 설정
    visited[x][y] = 1
    
    # 본인 칸에서 왼쪽으로 돌고 
    while 1:
      if tries == 4:
         dx, dy = moves[(direction-2) % 4] # 뒤로 가기
         if(board[x+dx][y+dy] == 1):
            break # 바다면 끝
         else:
            x += dx
            y += dy
            visited[x][y] = 1
         tries = 0 # 초기화 

      else:
         direction = (direction - 1) % 4 # 방향 전환 
         moves = [(-1, 0), (0, 1), (1, 0), (0, -1)] # 북 동 남 서
         dx, dy = moves[direction] # 방향 맞춰서 움직이기
         tries += 1
         if( board[x + dx][y + dy] == 0 and visited[x+dx][y+dy] == 0): # 갈 수 있으면 움직이기
            x += dx
            y += dy
            visited[x][y] = 1
            tries = 0
      
    for i in range(n):
      for j in range(m):
         if visited[i][j] == 1:
            count += 1


    return count


if __name__ == "__main__":
    n, m = map(int, input().split())
    x, y, direction = map(int, input().split())
    board = [list(map(int, input().split())) for _ in range(n)]
    print(solution(n, m, x, y, direction, board))
